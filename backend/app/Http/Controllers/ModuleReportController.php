<?php

namespace App\Http\Controllers;

use App\Services\Reports\ModuleReportService;
use App\Support\Access;
use Illuminate\Http\Request;
use Illuminate\Support\Str;
use Symfony\Component\HttpFoundation\StreamedResponse;

/**
 * The generic endpoint for the module report pack.
 *
 * There is one controller for every report in the application, because there
 * is one report definition for every report in the application. The
 * definitions live in App\Support\Reports\Registry; this controller only
 * knows how to hand one of them to the engine and how to give the result
 * back.
 *
 *   GET /module-reports                        the catalogue the user may open
 *   GET /module-reports/{module}/{report}      run one report
 *   GET /module-reports/{module}/{report}/export   the same report as CSV or PDF
 *
 * Access is decided per report, not per controller: a report names the
 * permission it needs, and the engine refuses to run it for anyone who does
 * not hold it. The catalogue is filtered the same way, so a user is never
 * shown a report they cannot open.
 */
class ModuleReportController extends Controller
{
    public function __construct(protected ModuleReportService $reports)
    {
        parent::__construct();
    }

    /**
     * The catalogue: every module and report the signed-in user may open.
     */
    public function catalog(Request $request)
    {
        return response()->json($this->reports->catalog($request->user()));
    }

    /**
     * Run one report and hand back the generic payload.
     *
     * Filters arrive as query parameters; the engine keeps only the ones the
     * report declared and binds every value.
     */
    public function run(Request $request, string $module, string $report)
    {
        $payload = $this->reports->run($module, $report, $request->query(), $request->user());

        return response()->json($payload);
    }

    /**
     * The same report as a file.
     *
     * Exporting is a separate permission from viewing - a report pack is
     * often read on screen, but taking the numbers out of the building is a
     * separate decision.
     */
    public function export(Request $request, string $module, string $report)
    {
        $user = $request->user();

        if (! Access::can($user, 'reports.export')) {
            abort(403, 'You do not have permission to export reports.');
        }

        $format = strtolower((string) $request->query('format', 'csv'));

        if (! in_array($format, ['csv', 'pdf'], true)) {
            abort(422, 'Unsupported export format. Use csv or pdf.');
        }

        $payload = $this->reports->run($module, $report, $request->query(), $user);

        $name = Str::slug($payload['report']['label'] ?? $module . '-' . $report) ?: 'report';

        return $format === 'pdf'
            ? $this->pdf($payload, $name, $user)
            : $this->csv($payload, $name, $user);
    }

    /* ------------------------------------------------------------------ */
    /* Output formats                                                      */
    /* ------------------------------------------------------------------ */

    /**
     * The report as a CSV file.
     *
     * The file opens with a small block describing the report - what it is,
     * when it was taken and which filters were applied - and then the table
     * itself, so a spreadsheet always says what it is holding.
     */
    protected function csv(array $payload, string $name, $user): StreamedResponse
    {
        $columns = $payload['report']['columns'] ?? [];

        $headers = [
            'Content-Type' => 'text/csv; charset=UTF-8',
            'Cache-Control' => 'no-store, no-cache',
        ];

        return response()->streamDownload(function () use ($payload, $columns, $user) {
            $handle = fopen('php://output', 'w');

            // A BOM so Excel reads the file as UTF-8 rather than as the
            // local code page.
            fwrite($handle, "\xEF\xBB\xBF");

            $this->csvRow($handle, ['Report', $payload['report']['label'] ?? '']);

            if (! empty($payload['report']['description'])) {
                $this->csvRow($handle, ['Description', $payload['report']['description']]);
            }

            $this->csvRow($handle, ['Module', $payload['report']['module_label'] ?? '']);
            $this->csvRow($handle, ['Generated', now()->format('d-m-Y H:i')]);
            $this->csvRow($handle, ['Generated by', $user?->name ?? '']);

            $filters = [];
            foreach ($payload['filters'] ?? [] as $key => $value) {
                $filters[] = $key . '=' . (is_array($value) ? implode('|', $value) : $value);
            }
            $this->csvRow($handle, ['Filters', $filters ? implode('; ', $filters) : 'None']);

            $meta = $payload['meta'] ?? [];
            $this->csvRow($handle, ['Rows', ($meta['total'] ?? 0) . ' (' . ($meta['returned'] ?? 0) . ' shown)']);

            $this->csvRow($handle, []);

            if (! empty($payload['summary'])) {
                foreach ($payload['summary'] as $figure) {
                    $this->csvRow($handle, [$figure['label'], $this->formatValue($figure['value'], $figure['format'] ?? 'number')]);
                }

                $this->csvRow($handle, []);
            }

            $this->csvRow($handle, array_column($columns, 'label'));

            foreach ($payload['rows'] as $row) {
                $line = [];
                foreach ($columns as $column) {
                    $line[] = $this->formatValue($row[$column['key']] ?? null, $column['format'] ?? 'text');
                }

                $this->csvRow($handle, $line);
            }

            fclose($handle);
        }, $name . '.csv', $headers);
    }

    /**
     * The report as a PDF file.
     */
    protected function pdf(array $payload, string $name, $user)
    {
        $pdf = \Barryvdh\DomPDF\Facade\Pdf::loadView('reports.module', [
            'payload' => $payload,
            'generated_at' => now()->format('d-m-Y H:i:s'),
            'generated_by' => $user?->name ?? '',
            'format' => fn ($value, string $format) => $this->formatValue($value, $format),
        ]);

        $filename = $name . '.pdf';

        return response()->streamDownload(function () use ($pdf) {
            echo $pdf->output();
        }, $filename, [
            'Content-Type' => 'application/pdf',
        ]);
    }

    /**
     * Write one CSV line.
     */
    protected function csvRow($handle, array $cells): void
    {
        fputcsv($handle, $cells);
    }

    /**
     * Render one value the way the column says it should be read.
     */
    protected function formatValue($value, string $format): string
    {
        if ($value === null) {
            return '';
        }

        switch ($format) {
            case 'money':
                return number_format((float) $value, 2);

            case 'percent':
                return number_format((float) $value, 2) . '%';

            case 'number':
                $number = (float) $value;
                return fmod($number, 1.0) === 0.0
                    ? number_format($number, 0)
                    : number_format($number, 2);

            case 'boolean':
                return $value ? 'Yes' : 'No';

            case 'date':
                return $this->formatDate((string) $value);

            case 'datetime':
                return $this->formatDateTime((string) $value);

            default:
                return (string) $value;
        }
    }

    /**
     * A book date, written the way the rest of the application writes it.
     */
    protected function formatDate(string $value): string
    {
        $date = \DateTime::createFromFormat('Y-m-d', substr($value, 0, 10));

        return $date ? $date->format('d/m/Y') : $value;
    }

    /**
     * A book timestamp.
     */
    protected function formatDateTime(string $value): string
    {
        $date = \DateTime::createFromFormat('Y-m-d H:i:s', substr($value, 0, 19));

        if (! $date) {
            $date = \DateTime::createFromFormat('Y-m-d H:i', substr($value, 0, 16));
        }

        return $date ? $date->format('d/m/Y H:i') : $value;
    }
}
